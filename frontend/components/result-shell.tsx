function isRecord(value: unknown): value is JsonRecord {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}

function printable(value: unknown): string {
  if (typeof value === "string") return value;
  if (typeof value === "number" || typeof value === "boolean") return String(value);
  try {
    return JSON.stringify(value, null, 2);
  } catch {
    return String(value);
  }
}

function redactTechnicalPaths(value: unknown): unknown {
  if (Array.isArray(value)) return value.map(redactTechnicalPaths);
  if (!isRecord(value)) return value;
  return Object.fromEntries(
    Object.entries(value)
      .filter(([key]) => !["path", "filename"].includes(key.toLowerCase()))
      .map(([key, nested]) => [key, redactTechnicalPaths(nested)]),
  );
}

function getVerdictCopy(verdict: string, t: Record<string, string>) {
  if (verdict === "Likely AI") return { label: t.likely, icon: "◈", copy: t.likelyBrief, tone: "rose" };
  if (verdict === "No AI signs found") return { label: t.noSigns, icon: "○", copy: t.noSignsBrief, tone: "emerald" };
  return { label: t.inconclusive, icon: "?", copy: t.inconclusiveBrief, tone: "amber" };
}

function getMediaType(result: ResultData): "image" | "video" | null {
  const summary = result.tool_summaries ?? {};
  const explicit =
    result.media_type ??
    result.mediaType ??
    result.media ??
    summary.media_type ??
    summary.mediaType;
  if (typeof explicit === "string") {
    const normalized = explicit.toLowerCase();
    if (normalized.includes("video")) return "video";
    if (normalized.includes("image") || normalized.includes("photo")) return "image";
  }

  const trace = Array.isArray(result.trace) ? result.trace : [];
  const videoTrace = trace.some(
    (step) => typeof step?.step === "string" && step.step.toLowerCase().includes("video"),
  );
  const videoSummary = Object.keys(summary).some((key) => key.toLowerCase().includes("video"));
  if (videoTrace || videoSummary) return "video";

  if (summary.quality || summary.provenance || summary.tiles || summary.robustness) return "image";
  return null;
}

function getSignalRange(result: ResultData): [number, number] | null {
  const calibration = isRecord(result.calibration) ? result.calibration : null;
  if (calibration?.status !== "calibrated") return null;
  const range = result.ai_signal_range ?? result.signal_range ?? calibration.range;
  if (
    Array.isArray(range) &&
    range.length === 2 &&
    range.every((value) => typeof value === "number" && Number.isFinite(value))
  ) {
    return [range[0] as number, range[1] as number];
  }
  return null;
}

function summarizeCheck(step: TraceStep): string {
  if (!isRecord(step.result)) return printable(step.result ?? "Completed");
  const visible = Object.entries(step.result)
    .filter(([key, value]) => key !== "path" && key !== "filename" && value !== null && value !== undefined)
    .slice(0, 5)
    .map(([key, value]) => `${key.replaceAll("_", " ")}: ${typeof value === "object" ? "[available]" : printable(value)}`);
  return visible.join(" · ") || "Completed";
}

